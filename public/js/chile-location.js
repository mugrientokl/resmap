window.inicializarSelectorTelefono = function (selectorId, inputId) {
    const selector = document.getElementById(selectorId);
    const input = document.getElementById(inputId);
    if (!selector || !input) return;

    const prefijoInicial = selector.value || '+569';
    selector.replaceChildren();
    window.paisesTelefono.forEach(([bandera, prefijo, pais]) => {
        selector.add(new Option(`${prefijo} ${pais}`, prefijo, false, prefijo === prefijoInicial));
    });
    selector.className = 'sr-only';
    selector.style.display = 'none';

    const contenedor = document.createElement('div');
    contenedor.className = 'relative shrink-0';
    contenedor.style.width = '76px';
    selector.parentElement.insertBefore(contenedor, selector);
    contenedor.append(selector);

    const boton = document.createElement('button');
    boton.type = 'button';
    boton.className = 'flex h-full w-full items-center gap-1 border border-gray-300 bg-white px-2 text-left text-sm font-medium';
    boton.style.height = `${input.offsetHeight || 46}px`;
    boton.style.borderRadius = '0.375rem 0 0 0.375rem';
    boton.setAttribute('aria-label', 'Seleccionar código de país');
    boton.setAttribute('aria-expanded', 'false');

    const menu = document.createElement('div');
    menu.className = 'absolute left-0 top-full z-50 hidden overflow-y-auto border border-gray-300 bg-white shadow-lg';
    menu.style.maxHeight = '240px';
    menu.style.width = '260px';

    const codigoBandera = bandera => [...bandera].map(caracter => String.fromCodePoint(caracter.codePointAt(0) - 127397).toLowerCase()).join('');
    const mostrarSeleccion = (paisSeleccionado, prefijoSeleccionado) => {
        const imagen = document.createElement('img');
        imagen.src = `https://flagcdn.com/w20/${codigoBandera(paisSeleccionado[0])}.png`;
        imagen.alt = '';
        imagen.width = 20;
        imagen.height = 14;
        imagen.style.objectFit = 'cover';
        boton.replaceChildren(imagen, document.createTextNode(prefijoSeleccionado));
        boton.title = paisSeleccionado[2];
    };

    window.paisesTelefono.forEach(pais => {
        const opcion = document.createElement('button');
        opcion.type = 'button';
        opcion.className = 'flex w-full items-center gap-2 px-3 py-2 text-left text-sm hover:bg-gray-100';
        const imagen = document.createElement('img');
        imagen.src = `https://flagcdn.com/w20/${codigoBandera(pais[0])}.png`;
        imagen.alt = '';
        imagen.width = 20;
        imagen.height = 14;
        imagen.style.objectFit = 'cover';
        opcion.append(imagen, document.createTextNode(`${pais[1]} ${pais[2]}`));
        opcion.addEventListener('click', () => {
            selector.value = pais[1];
            mostrarSeleccion(pais, pais[1]);
            menu.classList.add('hidden');
            boton.setAttribute('aria-expanded', 'false');
        });
        menu.append(opcion);
    });

    const paisInicial = window.paisesTelefono.find(pais => pais[1] === prefijoInicial) || window.paisesTelefono[0];
    mostrarSeleccion(paisInicial, paisInicial[1]);
    boton.addEventListener('click', event => {
        event.stopPropagation();
        menu.classList.toggle('hidden');
        boton.setAttribute('aria-expanded', String(!menu.classList.contains('hidden')));
    });
    document.addEventListener('click', () => {
        menu.classList.add('hidden');
        boton.setAttribute('aria-expanded', 'false');
    });
    contenedor.append(boton, menu);
    input.title = 'Ingresa los 8 dígitos de tu número local';
};

window.inicializarUbicacionChile = function (regionId, comunaId, regionInicial = '', comunaInicial = '') {
    const region = document.getElementById(regionId);
    const comuna = document.getElementById(comunaId);
    if (!region || !comuna) return;

    Object.keys(window.chileRegions).forEach(nombre => {
        region.add(new Option(nombre, nombre, false, nombre === regionInicial));
    });

    const actualizarComunas = () => {
        const comunas = window.chileRegions[region.value] || [];
        comuna.replaceChildren(new Option('Selecciona una comuna', '', true, !comunaInicial));
        comunas.forEach(nombre => comuna.add(new Option(nombre, nombre, false, nombre === comunaInicial)));
        comuna.disabled = comunas.length === 0;
    };

    region.addEventListener('change', () => {
        comunaInicial = '';
        actualizarComunas();
    });
    actualizarComunas();
};

window.inicializarFormularioCatalogo = function () {
    const form = document.querySelector('#solicitud-modal form');
    const telefono = form?.querySelector('#telefono');
    const submit = form?.querySelector('button');
    if (!form || !telefono || !submit) return;

    const prefijo = document.createElement('select');
    prefijo.id = 'prefijo_telefono';
    prefijo.name = 'prefijo_telefono';
    prefijo.className = 'rounded-l-md border border-[#d9aaa3] bg-white p-3 font-bold text-[#8f241d]';
    telefono.parentElement.querySelector('span')?.remove();
    telefono.parentElement.replaceChild(prefijo, telefono);
    prefijo.parentElement.append(telefono);
    telefono.classList.add('rounded-r-md', 'border-l-0');
    inicializarSelectorTelefono('prefijo_telefono', 'telefono');

    const nombre = form.querySelector('input[name="nombre"]');
    if (nombre) {
        nombre.style.height = '46px';
        nombre.style.alignSelf = 'start';
    }

    const regionWrapper = document.createElement('div');
    regionWrapper.innerHTML = '<select id="region_solicitud" name="region" required class="w-full border border-[#d9aaa3] bg-white p-3 text-[#241817]"><option value="">Selecciona una región</option></select>';
    const comunaWrapper = document.createElement('div');
    comunaWrapper.innerHTML = '<select id="comuna_solicitud" name="comuna" required disabled class="w-full border border-[#d9aaa3] bg-white p-3 text-[#241817]"><option value="">Selecciona una comuna</option></select>';
    submit.before(regionWrapper, comunaWrapper);
    inicializarUbicacionChile('region_solicitud', 'comuna_solicitud');
};